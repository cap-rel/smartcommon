import { Title, ArgTypes, Description, Canvas, Source } from "@storybook/addon-docs/blocks";

import usage from "../../usage.json";

// Pages whose title does not end with the exported name.
const USAGE_ALIASES = {
    "Components/Formats/Array": "ArrayFormat",
};

// Stories of the page other than Default, the variants (Variants page) and
// the props playground: the usage examples ("With QR pair", "Read only"...).
// Without this section they were hidden everywhere, their "!dev" tag keeping
// them out of the sidebar.
const exampleStories = (of) => Object.entries(of ?? {}).filter(([key, story]) => (
    key !== "default"
    && key !== "Default"
    && /^[A-Z]/.test(key)
    && story !== null
    && typeof story === "object"
    && !["variant", "test"].includes(story.parameters?.storyKind)
));

const exampleTitle = (key, story) => story.name ?? key.replace(/([a-z0-9])([A-Z])/g, "$1 $2");

const formatDate = (iso) => {
    const [year, month, day] = `${iso ?? ""}`.split("-");
    return year && month && day ? `${day}/${month}/${year}` : iso;
};

// "Utilisé dans": the consumer projects importing this component, from
// usage.json (regenerated by `npm run usage` before publishing the site).
export const UsedIn = ({ title }) => {
    if (!title) return null;

    const name = USAGE_ALIASES[title] ?? title.split("/").pop();
    const entries = Object.entries(usage.components?.[name] ?? {});
    const total = usage.projects?.length ?? 0;

    return (
        <div className="sc-usage">
            <div className="h2" style={{ fontSize: "13px" }}>Utilisé dans</div>
            {entries.length > 0 ? (
                <ul className="sc-usage-list">
                    {entries.map(([project, files]) => (
                        <li key={project}>
                            <strong>{project}</strong>
                            <span>{files} {files > 1 ? "fichiers" : "fichier"}</span>
                        </li>
                    ))}
                </ul>
            ) : (
                <p className="sc-usage-empty">{`Aucun des ${total} projets relevés ne l'importe pour l'instant.`}</p>
            )}
            <p className="sc-usage-meta">
                Relevé du {formatDate(usage.scannedAt)} sur {total} projets
                {entries.length > 0 && ` : ${entries.length} ${entries.length > 1 ? "l'importent" : "l'importe"}`}.
            </p>
        </div>
    );
};

export const Examples = ({ of }) => {
    const examples = exampleStories(of);
    if (examples.length === 0) return null;

    return (
        <div className="sc-examples">
            <div className="h2" style={{ fontSize: "13px" }}>Examples</div>
            {examples.map(([key, story]) => (
                <div key={key} className="sc-example">
                    <h3 className="sc-example-title">{exampleTitle(key, story)}</h3>
                    <Description of={story} />
                    <Canvas of={story} />
                </div>
            ))}
        </div>
    );
};

export const PropsPage = (props) => {
    const { of } = props;
    return (
        <>
            <Title />
            <Description />

            {of?.Default && <Canvas sourceState="none" of={of.Default} />}

            {of?.Default && <Source of={of.Default} />}

            <Examples of={of} />

            <UsedIn title={of?.default?.title} />

            <div className="h2" style={{ fontSize: "13px" }}>Props</div>
            <ArgTypes />
        </>
    );
};
